// Самопроверка QA: сценарий с ожиданием, которое на фикстуре не выполняется (должен дать failed).
export default {
  title: 'Фикстура: ожидание, которого нет',
  adapter: 'basic',
  langs: ['ru'],
  size: '375x740',
  steps: [
    {
      name: 'Нажать «Готово» и ждать текст «Верно»',
      run: async (qa) => {
        qa.click('#done', 'кнопка «Готово»');
        await qa.sleep(300);
        qa.expect(qa.text('#msg') === 'Верно', 'после нажатия видно «Верно»', { фактически: qa.text('#msg') });
      },
    },
    { name: 'Шаг после провала (не выполняется)', run: async (qa) => { qa.note('не должен выполниться'); } },
  ],
};
